-- ============================================================================
--  DH 스마트파워 변압기 통합 모니터링 시스템
--  PostgreSQL 스키마  (Supabase 제거 후 자체 구축용)
--
--  적용:  psql "$DATABASE_URL" -f db/schema.sql
--  이 파일은 반복 실행해도 안전합니다 (IF NOT EXISTS / OR REPLACE).
