-- ----------------------------------------------------------------------------
-- 7. 알람 발송 (메신저 · 문자 · 메일)
--    알람이 생기면 등록된 수신자에게 각자 지정한 경로로 보냅니다.
--    반복 실행해도 안전합니다.
-- ----------------------------------------------------------------------------

-- 채널별 연동 정보. config 에는 API 키 같은 비밀값이 들어가므로
-- 화면으로는 절대 그대로 내려보내지 않고 가린 값만 보여줍니다.
CREATE TABLE IF NOT EXISTS notify_channels (
  channel    text PRIMARY KEY
             CHECK (channel IN ('telegram', 'sms', 'kakao', 'email', 'whatsapp')),
  enabled    boolean NOT NULL DEFAULT false,
  config     jsonb   NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid REFERENCES users(id) ON DELETE SET NULL
);

INSERT INTO notify_channels (channel) VALUES
  ('telegram'), ('sms'), ('kakao'), ('email'), ('whatsapp')
ON CONFLICT (channel) DO NOTHING;

-- 수신자. 한 사람이 여러 경로로 받도록 여러 줄을 등록할 수 있습니다.
CREATE TABLE IF NOT EXISTS notify_recipients (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  channel    text NOT NULL
             CHECK (channel IN ('telegram', 'sms', 'kakao', 'email', 'whatsapp')),
  -- 전화번호 · 텔레그램 chat_id · 메일 주소
  target     text NOT NULL,
  -- 이 등급 이상일 때만 보냅니다.
  min_level  text NOT NULL DEFAULT 'warning'
             CHECK (min_level IN ('caution', 'warning', 'danger')),
  -- 야간 미발송 구간(시). 둘 다 NULL 이면 항상 발송합니다.
  -- 위험(danger) 등급은 이 구간에도 보냅니다.
  quiet_from smallint CHECK (quiet_from BETWEEN 0 AND 23),
  quiet_to   smallint CHECK (quiet_to   BETWEEN 0 AND 23),
  enabled    boolean NOT NULL DEFAULT true,
  memo       text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 같은 경로에 같은 번호를 두 번 등록해 중복 발송되는 일을 막습니다.
CREATE UNIQUE INDEX IF NOT EXISTS notify_recipients_uniq
  ON notify_recipients (channel, target);

-- 발송 이력. 성공·실패·건너뜀을 모두 남겨 추적할 수 있게 합니다.
CREATE TABLE IF NOT EXISTS notify_log (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alarm_id     bigint,
  recipient_id bigint,
  recipient    text,
  channel      text NOT NULL,
  target       text NOT NULL,
  level        text,
  body         text NOT NULL,
  status       text NOT NULL CHECK (status IN ('sent', 'failed', 'skipped')),
  error        text,
  provider_id  text,
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS notify_log_created_idx ON notify_log (created_at DESC);
CREATE INDEX IF NOT EXISTS notify_log_alarm_idx   ON notify_log (alarm_id);

-- 같은 알람을 워커가 두 번 집어도 한 번만 보내도록, 처리 완료 표시를 둡니다.
CREATE TABLE IF NOT EXISTS notify_dispatched (
  alarm_id     bigint PRIMARY KEY,
  dispatched_at timestamptz NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- 8. 수집 연동 (브로커 설정 · 수신 내역 · 장비 명령)
--    반복 실행해도 안전합니다.
-- ----------------------------------------------------------------------------

-- 브로커 접속 정보. 수집기가 기동 시와 주기적으로 읽어 반영합니다.
-- 비밀번호가 들어가므로 화면으로는 설정 여부만 내려보냅니다.
CREATE TABLE IF NOT EXISTS mqtt_config (
  id            integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  host          text    NOT NULL DEFAULT '127.0.0.1',
  port          integer NOT NULL DEFAULT 1883,
  username      text,
  password      text,
  tls           boolean NOT NULL DEFAULT false,
  ca_path       text,
  client_id     text    NOT NULL DEFAULT 'dh-collector',
  topic_prefix  text    NOT NULL DEFAULT 'dh/v1',
  site          text    NOT NULL DEFAULT 'dh1',
  -- 수신 내역을 며칠 보관할지. 지난 것은 수집기가 스스로 지웁니다.
  keep_log_days integer NOT NULL DEFAULT 7,
  version       integer NOT NULL DEFAULT 1,
  updated_at    timestamptz NOT NULL DEFAULT now(),
  updated_by    uuid REFERENCES users(id) ON DELETE SET NULL
);

INSERT INTO mqtt_config (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- 수집기가 살아 있는지, 브로커에 붙어 있는지 화면에서 보기 위한 자리입니다.
CREATE TABLE IF NOT EXISTS collector_status (
  id              integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  connected       boolean NOT NULL DEFAULT false,
  broker          text,
  last_error      text,
  started_at      timestamptz,
  last_heartbeat  timestamptz,
  last_message_at timestamptz,
  messages        bigint NOT NULL DEFAULT 0,
  rows_stored     bigint NOT NULL DEFAULT 0,
  alarms          bigint NOT NULL DEFAULT 0,
  errors          bigint NOT NULL DEFAULT 0,
  config_version  integer
);

INSERT INTO collector_status (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- 수신 내역. 장비가 실제로 무엇을 보냈는지 원문 그대로 남겨,
-- 규격이 맞지 않을 때 어느 쪽 문제인지 바로 확인할 수 있게 합니다.
CREATE TABLE IF NOT EXISTS ingest_log (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic        text NOT NULL,
  src_type     text,
  src_id       text,
  kind         text,
  device_ids   text[],
  item_count   integer NOT NULL DEFAULT 0,
  stored_count integer NOT NULL DEFAULT 0,
  replay       boolean NOT NULL DEFAULT false,
  status       text NOT NULL CHECK (status IN ('ok', 'warn', 'error')),
  message      text,
  payload      jsonb,
  received_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ingest_log_time_idx   ON ingest_log (received_at DESC);
CREATE INDEX IF NOT EXISTS ingest_log_status_idx ON ingest_log (status, received_at DESC);

-- 서버 → 장비 명령. 화면에서 넣으면 수집기가 집어 MQTT 로 내보냅니다.
CREATE TABLE IF NOT EXISTS device_commands (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site         text NOT NULL DEFAULT 'dh1',
  target_type  text NOT NULL CHECK (target_type IN ('bridge', 'module', 'gateway')),
  target_id    text NOT NULL,
  -- 특정 설비 하나를 지정할 때만 씁니다.
  device_id    text,
  command      text NOT NULL,
  params       jsonb NOT NULL DEFAULT '{}'::jsonb,
  status       text NOT NULL DEFAULT 'pending'
               CHECK (status IN ('pending', 'sent', 'acked', 'failed', 'timeout')),
  requested_by uuid REFERENCES users(id) ON DELETE SET NULL,
  requested_at timestamptz NOT NULL DEFAULT now(),
  sent_at      timestamptz,
  acked_at     timestamptz,
  ack          jsonb,
  error        text
);

CREATE INDEX IF NOT EXISTS device_commands_time_idx   ON device_commands (requested_at DESC);
CREATE INDEX IF NOT EXISTS device_commands_status_idx ON device_commands (status, requested_at);

-- 명령이 들어오면 수집기가 곧바로 내보내도록 통지합니다.
CREATE OR REPLACE FUNCTION notify_device_command() RETURNS trigger AS $$
BEGIN
  PERFORM pg_notify('device_command', NEW.id::text);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS device_commands_notify ON device_commands;
CREATE TRIGGER device_commands_notify
  AFTER INSERT ON device_commands
  FOR EACH ROW EXECUTE FUNCTION notify_device_command();

-- 브로커 설정이 바뀌면 수집기가 다시 접속하도록 통지합니다.
CREATE OR REPLACE FUNCTION notify_mqtt_config() RETURNS trigger AS $$
BEGIN
  PERFORM pg_notify('mqtt_config', NEW.version::text);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS mqtt_config_notify ON mqtt_config;
CREATE TRIGGER mqtt_config_notify
  AFTER UPDATE ON mqtt_config
  FOR EACH ROW EXECUTE FUNCTION notify_mqtt_config();

-- ----------------------------------------------------------------------------
-- 9. 장비 구성 3안 수용  (㈜헤디 2026-10 협의 반영)
--
--    1안  측정모듈 → (MQTT) → 서버
--    2안  측정모듈 → (RS-485) → 사용자 PC → (MQTT) → 서버
--    3안  측정모듈 → (RS-485) → 브릿지 → (MQTT) → 서버
--
--    세 경우 모두 "설비(측정모듈)" 는 devices 에, 그 앞단에서 값을 모아
--    보내는 주체(브릿지 · PC 게이트웨이)는 bridges 에 담습니다.
--    1안은 앞단이 없으므로 devices.bridge_id 가 NULL 로 남습니다.
--    이 절은 반복 실행해도 안전합니다.
-- ----------------------------------------------------------------------------

-- 값을 모아 보내는 주체의 종류. 2안의 사용자 PC 도 여기에 들어갑니다.
ALTER TABLE bridges ADD COLUMN IF NOT EXISTS kind text NOT NULL DEFAULT 'bridge';
ALTER TABLE bridges DROP CONSTRAINT IF EXISTS bridges_kind_check;
ALTER TABLE bridges ADD CONSTRAINT bridges_kind_check
  CHECK (kind IN ('bridge', 'gateway'));

-- RS-485 한 가닥에 붙일 수 있는 최대 대수. 헤디 회신 기준 32대입니다.
ALTER TABLE bridges ADD COLUMN IF NOT EXISTS max_devices integer NOT NULL DEFAULT 32;

-- 설비가 서버까지 어떤 길로 오는지. 화면에서 구성을 구분해 보여주기 위한 값입니다.
ALTER TABLE devices ADD COLUMN IF NOT EXISTS link_type text NOT NULL DEFAULT 'bridge';
ALTER TABLE devices DROP CONSTRAINT IF EXISTS devices_link_type_check;
ALTER TABLE devices ADD CONSTRAINT devices_link_type_check
  CHECK (link_type IN ('direct', 'bridge', 'gateway'));

-- 1안처럼 모듈이 직접 붙는 경우, 모듈 자신의 접속 상태를 여기에 적습니다.
ALTER TABLE devices ADD COLUMN IF NOT EXISTS online       boolean NOT NULL DEFAULT false;
ALTER TABLE devices ADD COLUMN IF NOT EXISTS last_seen_at timestamptz;
ALTER TABLE devices ADD COLUMN IF NOT EXISTS fw_version   text;
ALTER TABLE devices ADD COLUMN IF NOT EXISTS rssi         integer;
-- 장치에 설정된 측정 주기(초). 측정 주기 변경 명령이 성공하면 갱신됩니다.
ALTER TABLE devices ADD COLUMN IF NOT EXISTS interval_sec integer;

-- 앞단별 등록 대수를 세기 위한 색인입니다.
CREATE INDEX IF NOT EXISTS devices_bridge_idx ON devices (bridge_id);

-- 명령 응답 대기시간. 헤디 회신은 1초 이내이지만, 네트워크 왕복과
-- 브로커 지연을 감안해 기본 10초로 두고 화면에서 조정합니다.
ALTER TABLE mqtt_config ADD COLUMN IF NOT EXISTS ack_timeout_sec integer NOT NULL DEFAULT 10;

-- 재전송(미전송분 백필) 한 메시지에 담을 수 있는 최대 항목 수.
-- 브릿지가 최대 1개월분을 보관하므로, 한 번에 쏟아지지 않도록 상한을 둡니다.
ALTER TABLE mqtt_config ADD COLUMN IF NOT EXISTS max_replay_items integer NOT NULL DEFAULT 500;

-- 수신 내역의 원문 보관 상한. 재전송 메시지는 원문이 매우 크므로
-- 이 수를 넘는 항목은 요약만 남깁니다.
ALTER TABLE mqtt_config ADD COLUMN IF NOT EXISTS log_payload_items integer NOT NULL DEFAULT 20;

-- 유면 저하를 몇 등급으로 볼지. 웹 화면과 수집 서버가 같은 값을 씁니다.
-- (유면 규격은 헤디와 협의 중이며, 아날로그로 확정되면 임계치로 바뀝니다.)
UPDATE app_config
   SET thresholds = thresholds || '{"oilLowLevel": "warning"}'::jsonb
 WHERE id = 1 AND NOT (thresholds ? 'oilLowLevel');

-- 기존 데이터 정리: 앞단이 없는 설비는 직결로 표시합니다.
UPDATE devices SET link_type = 'direct' WHERE bridge_id IS NULL AND link_type = 'bridge';

-- 설비 목록이 바뀌면 수집기가 곧바로 다시 읽도록 통지합니다.
-- (화면에서 설비를 지운 직후 그 설비의 값이 들어오면, 수집기가 아직
--  예전 목록을 들고 있어 적재에 실패하는 일을 막습니다.)
CREATE OR REPLACE FUNCTION notify_devices_changed() RETURNS trigger AS $$
BEGIN
  PERFORM pg_notify('devices_changed', COALESCE(NEW.device_id, OLD.device_id));
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS devices_changed_notify ON devices;
CREATE TRIGGER devices_changed_notify
  AFTER INSERT OR DELETE ON devices
  FOR EACH ROW EXECUTE FUNCTION notify_devices_changed();
